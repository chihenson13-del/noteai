-- NoteAI schema: users (profiles), recordings, transcripts, summaries, action items, jobs.
-- Every table is protected by Row Level Security: a user can only see and change their own rows.
-- Writes that decide processing results (transcripts, job state) are reserved for the
-- service role used by the `process-recording` Edge Function.

-- ---------------------------------------------------------------------------
-- profiles
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id) values (new.id) on conflict do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- recordings
-- `id` is generated by the client, so retrying an upload can never create a second row.
-- ---------------------------------------------------------------------------
create table public.recordings (
  id uuid primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  duration_ms integer not null default 0 check (duration_ms >= 0),
  size_bytes bigint not null default 0 check (size_bytes >= 0),
  mime_type text not null default 'audio/webm',
  quality text not null default 'standard' check (quality in ('economy', 'standard', 'high')),
  status text not null default 'uploading'
    check (status in ('uploading', 'uploaded', 'transcribing', 'summarizing', 'completed', 'failed')),
  failed_stage text check (failed_stage in ('upload', 'transcribe', 'summarize')),
  error_message text check (char_length(error_message) <= 500),
  storage_path text,
  checksum_sha256 text check (checksum_sha256 ~ '^[0-9a-f]{64}$'),
  language text,
  was_interrupted boolean not null default false,
  interruption_note text,
  audio_deleted_at timestamptz,
  recorded_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index recordings_user_recorded_idx on public.recordings (user_id, recorded_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger recordings_touch_updated_at
  before update on public.recordings
  for each row execute function public.touch_updated_at();

-- Clients may only move a recording through the *upload* part of its lifecycle. Transcription
-- and summarization status is owned by the server.
create or replace function public.guard_recording_client_update()
returns trigger
language plpgsql
as $$
begin
  if coalesce(auth.role(), '') = 'service_role' or current_user in ('postgres', 'supabase_admin', 'service_role') then
    return new;
  end if;

  if new.id <> old.id or new.user_id <> old.user_id then
    raise exception 'id and user_id are immutable';
  end if;

  if new.status is distinct from old.status then
    if not (
      (new.status in ('uploading', 'uploaded') and old.status in ('uploading', 'uploaded', 'failed'))
      or (new.status = 'failed' and new.failed_stage = 'upload' and old.status in ('uploading', 'uploaded', 'failed'))
    ) then
      raise exception 'status transition % -> % is not allowed for clients', old.status, new.status;
    end if;
  end if;

  return new;
end;
$$;

create trigger recordings_guard_client_update
  before update on public.recordings
  for each row execute function public.guard_recording_client_update();

-- ---------------------------------------------------------------------------
-- transcripts (written only by the server)
-- ---------------------------------------------------------------------------
create table public.transcripts (
  recording_id uuid primary key references public.recordings (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  language text,
  full_text text not null,
  segments jsonb not null default '[]'::jsonb,
  provider text not null,
  model text not null,
  created_at timestamptz not null default now(),
  search_vector tsvector generated always as (to_tsvector('simple', full_text)) stored
);

create index transcripts_user_idx on public.transcripts (user_id);
create index transcripts_search_idx on public.transcripts using gin (search_vector);

-- ---------------------------------------------------------------------------
-- summaries (created by the server, editable by the owner)
-- ---------------------------------------------------------------------------
create table public.summaries (
  recording_id uuid primary key references public.recordings (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  summary text not null default '',
  key_takeaways jsonb not null default '[]'::jsonb,
  decisions jsonb not null default '[]'::jsonb,
  topics jsonb not null default '[]'::jsonb,
  provider text not null,
  model text not null,
  user_edited boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger summaries_touch_updated_at
  before update on public.summaries
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- action items
-- ---------------------------------------------------------------------------
create table public.action_items (
  id uuid primary key default gen_random_uuid(),
  recording_id uuid not null references public.recordings (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  text text not null check (char_length(text) between 1 and 600),
  assignee text,
  due_date date,
  done boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index action_items_recording_idx on public.action_items (recording_id, sort_order);

-- ---------------------------------------------------------------------------
-- processing jobs: at most ONE running job per recording (duplicate-processing guard)
-- ---------------------------------------------------------------------------
create table public.processing_jobs (
  id uuid primary key default gen_random_uuid(),
  recording_id uuid not null references public.recordings (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  kind text not null check (kind in ('pipeline', 'summarize')),
  status text not null default 'running' check (status in ('running', 'succeeded', 'failed')),
  error text,
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create unique index processing_jobs_one_running_idx
  on public.processing_jobs (recording_id)
  where status = 'running';

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.recordings enable row level security;
alter table public.transcripts enable row level security;
alter table public.summaries enable row level security;
alter table public.action_items enable row level security;
alter table public.processing_jobs enable row level security;

create policy "profiles: read own" on public.profiles for select to authenticated using (id = auth.uid());
create policy "profiles: update own" on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

create policy "recordings: read own" on public.recordings for select to authenticated using (user_id = auth.uid());
create policy "recordings: insert own" on public.recordings for insert to authenticated with check (user_id = auth.uid());
create policy "recordings: update own" on public.recordings for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "recordings: delete own" on public.recordings for delete to authenticated using (user_id = auth.uid());

create policy "transcripts: read own" on public.transcripts for select to authenticated using (user_id = auth.uid());

create policy "summaries: read own" on public.summaries for select to authenticated using (user_id = auth.uid());
create policy "summaries: update own" on public.summaries for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

create policy "action_items: read own" on public.action_items for select to authenticated using (user_id = auth.uid());
create policy "action_items: insert own" on public.action_items for insert to authenticated
  with check (
    user_id = auth.uid()
    and exists (select 1 from public.recordings r where r.id = recording_id and r.user_id = auth.uid())
  );
create policy "action_items: update own" on public.action_items for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "action_items: delete own" on public.action_items for delete to authenticated using (user_id = auth.uid());

create policy "processing_jobs: read own" on public.processing_jobs for select to authenticated using (user_id = auth.uid());

-- Column-level hardening: owners may edit the content of their notes, nothing else.
revoke update on public.summaries from authenticated;
grant update (summary, key_takeaways, decisions, topics, user_edited) on public.summaries to authenticated;
