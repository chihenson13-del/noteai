#!/usr/bin/env node
/**
 * Generates NoteAI access codes.
 *
 *   node scripts/generate-codes.mjs                 # 100 four-digit codes, one device each
 *   node scripts/generate-codes.mjs --long          # 16-character codes instead
 *   node scripts/generate-codes.mjs --count 50 --devices 2 --prefix "Team A"
 *
 * Writes:
 *   codes/access-codes.csv        number,label,code     <- give these to people (KEEP PRIVATE)
 *   codes/access-codes.txt        printable list         <- same codes (KEEP PRIVATE)
 *   supabase/seed/access_codes.sql  INSERT of the SHA-256 HASHES only (safe to run in the SQL editor)
 *
 * The plain codes exist ONLY in the two files under codes/ (git-ignored). The database only
 * ever receives hashes. The script refuses to overwrite existing output so you cannot
 * accidentally replace codes you already handed out; pass --force to regenerate everything.
 *
 * The functions below mirror supabase/functions/_shared/accessCode.ts; a unit test keeps the
 * two implementations identical.
 */
import { createHash, randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const CODE_ALPHABET = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
export const CODE_LENGTH = 16;

export function normalizeCode(input) {
  return input
    .toUpperCase()
    .replace(/O/g, '0')
    .replace(/[IL]/g, '1')
    .replace(/[^0-9A-Z]/g, '');
}

export function formatCode(normalized) {
  return normalized.match(/.{1,4}/g)?.join('-') ?? '';
}

export function generateCode(random = (n) => randomBytes(n)) {
  let code = '';
  while (code.length < CODE_LENGTH) {
    for (const byte of random(CODE_LENGTH * 2)) {
      code += CODE_ALPHABET[byte & 31];
      if (code.length === CODE_LENGTH) break;
    }
  }
  return code;
}

/** A random 4-digit member code, 1000-9999. Mirrors generateShortCode in accessCode.ts. */
export function generateShortCode(random = (n) => randomBytes(n)) {
  for (;;) {
    const bytes = random(2);
    const value = (bytes[0] ?? 0) * 256 + (bytes[1] ?? 0);
    if (value < 63000) return String(1000 + (value % 9000));
  }
}

export function hashCode(code) {
  return createHash('sha256').update(`noteai-code:v1:${normalizeCode(code)}`).digest('hex');
}

/** @returns {{ number: number, label: string, code: string, hash: string }[]} */
export function generateBatch({ count, prefix, random, long = false }) {
  if (!long && count > 9000) throw new Error('There are only 9000 four-digit codes; use --long for more.');
  const seen = new Set();
  const rows = [];
  while (rows.length < count) {
    const code = long ? generateCode(random) : generateShortCode(random);
    if (seen.has(code)) continue; // astronomically unlikely, but never emit duplicates
    seen.add(code);
    const number = rows.length + 1;
    rows.push({ number, label: `${prefix} ${String(number).padStart(3, '0')}`, code, hash: hashCode(code) });
  }
  return rows;
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function buildSeedSql(rows, maxDevices) {
  const values = rows.map((r) => `  (${sqlString(r.hash)}, ${sqlString(r.label)}, ${maxDevices})`).join(',\n');
  return (
    `-- Generated by scripts/generate-codes.mjs. Contains HASHES only (no usable codes).\n` +
    `-- Safe to re-run: existing codes are left untouched.\n` +
    `insert into public.access_codes (code_hash, label, max_devices) values\n${values}\n` +
    `on conflict (code_hash) do nothing;\n`
  );
}

function parseArgs(argv) {
  const options = { count: 100, devices: 1, prefix: 'Code', force: false, out: 'codes', long: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    const next = () => argv[++i];
    if (arg === '--count') options.count = Number(next());
    else if (arg === '--devices') options.devices = Number(next());
    else if (arg === '--prefix') options.prefix = String(next());
    else if (arg === '--out') options.out = String(next());
    else if (arg === '--force') options.force = true;
    else if (arg === '--long') options.long = true;
    else throw new Error(`Unknown option: ${arg}`);
  }
  if (!Number.isInteger(options.count) || options.count < 1 || options.count > 5000) throw new Error('--count must be 1..5000');
  if (!Number.isInteger(options.devices) || options.devices < 1 || options.devices > 20) throw new Error('--devices must be 1..20');
  return options;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const outDir = resolve(root, options.out);
  const csvPath = resolve(outDir, 'access-codes.csv');
  const txtPath = resolve(outDir, 'access-codes.txt');
  const sqlPath = resolve(root, 'supabase', 'seed', 'access_codes.sql');

  if (!options.force && [csvPath, txtPath, sqlPath].some((p) => existsSync(p))) {
    console.error(
      'Output already exists, so nothing was changed (regenerating would invalidate codes you may have handed out).\n' +
        'Delete the files or pass --force to create a brand-new set.',
    );
    process.exit(1);
  }

  const rows = generateBatch({ count: options.count, prefix: options.prefix, long: options.long });
  mkdirSync(outDir, { recursive: true });
  mkdirSync(dirname(sqlPath), { recursive: true });

  writeFileSync(csvPath, `number,label,code\n${rows.map((r) => `${r.number},"${r.label}",${formatCode(r.code)}`).join('\n')}\n`);
  writeFileSync(
    txtPath,
    `NoteAI access codes (${rows.length}) - KEEP PRIVATE\n` +
      `Each code signs in on ${options.devices === 1 ? 'ONE device' : `up to ${options.devices} devices`}. ` +
      `The first time a device uses a code it asks for the person's full name and email.\n\n` +
      rows.map((r) => `${String(r.number).padStart(3, '0')}  ${formatCode(r.code)}`).join('\n') +
      '\n',
  );
  writeFileSync(sqlPath, buildSeedSql(rows, options.devices));

  console.log(`Generated ${rows.length} codes (${options.devices} device${options.devices === 1 ? '' : 's'} each).`);
  console.log(`  codes   : ${csvPath}\n            ${txtPath}   (private - do not commit or share publicly)`);
  console.log(`  database: ${sqlPath}   (hashes only - run this in the Supabase SQL editor)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
