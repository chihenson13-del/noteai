import { useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import { fetchSharedNotes, type SharedNotesResult } from '../../data/sharedNotes';
import { errorMessage } from '../../lib/errors';
import { formatDateTime, formatDuration, formatTimestamp } from '../../lib/format';
import { Banner, Spinner } from '../components/primitives';

/**
 * Public, read-only page behind a share link. It shows a snapshot of notes only — never the
 * audio or transcript — and is marked noindex.
 */
export function SharedNotesScreen() {
  const { token = '' } = useParams();
  const [result, setResult] = useState<SharedNotesResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const meta = document.createElement('meta');
    meta.name = 'robots';
    meta.content = 'noindex, nofollow';
    document.head.appendChild(meta);
    return () => meta.remove();
  }, []);

  useEffect(() => {
    let cancelled = false;
    setResult(null);
    setError(null);
    fetchSharedNotes(token)
      .then((r) => !cancelled && setResult(r))
      .catch((e) => !cancelled && setError(errorMessage(e, 'This link is invalid or has expired.')));
    return () => {
      cancelled = true;
    };
  }, [token]);

  if (error) {
    return (
      <main className="shared">
        <div className="shared-inner">
          <h1 className="h1 display">Notes unavailable</h1>
          <Banner tone="warning">{error}</Banner>
          <p className="muted small">If you expected to see notes here, ask the person who shared them to send a new link.</p>
        </div>
      </main>
    );
  }

  if (!result) {
    return (
      <main className="shared">
        <div className="shared-inner row muted" role="status">
          <Spinner /> Loading shared notes…
        </div>
      </main>
    );
  }

  const { snapshot, expiresAt } = result;

  return (
    <main className="shared">
      <article className="shared-inner stack" style={{ gap: 22 }}>
        <header className="stack" style={{ gap: 6 }}>
          <p className="eyebrow">Shared notes · read only</p>
          <h1 className="h1 display">{snapshot.title}</h1>
          <p className="muted small">
            {formatDateTime(snapshot.recordedAt)} · {formatDuration(snapshot.durationMs)} · link expires {formatDateTime(expiresAt)}
          </p>
        </header>

        <Banner tone="info">
          These notes were generated by AI ({snapshot.generatedBy.provider}, {snapshot.generatedBy.model})
          {snapshot.generatedBy.userEdited ? ' and edited by the author' : ''}. They may contain mistakes. The recording and transcript
          are not included.
        </Banner>

        {snapshot.summary && (
          <section className="card stack">
            <h2 className="h3">Summary</h2>
            <p className="prose" style={{ whiteSpace: 'pre-line' }}>{snapshot.summary}</p>
          </section>
        )}

        {snapshot.keyTakeaways.length > 0 && (
          <section className="card stack">
            <h2 className="h3">Key takeaways</h2>
            <ul className="note-list">
              {snapshot.keyTakeaways.map((item, index) => (
                <li key={index} className="note-item">
                  <span className="bullet" aria-hidden />
                  <span>{item.text}</span>
                </li>
              ))}
            </ul>
          </section>
        )}

        {snapshot.decisions.length > 0 && (
          <section className="card stack">
            <h2 className="h3">Decisions</h2>
            <ul className="note-list">
              {snapshot.decisions.map((item, index) => (
                <li key={index} className="note-item">
                  <span className="bullet" aria-hidden />
                  <span>{item.text}</span>
                </li>
              ))}
            </ul>
          </section>
        )}

        {snapshot.actionItems.length > 0 && (
          <section className="card stack">
            <h2 className="h3">Action items</h2>
            <ul className="note-list">
              {snapshot.actionItems.map((item, index) => (
                <li key={index} className="note-item">
                  <span aria-hidden>{item.done ? '☑' : '☐'}</span>
                  <span className="grow">
                    {item.text}
                    {(item.assignee || item.dueDate) && (
                      <span className="muted small">
                        {' '}
                        — {[item.assignee, item.dueDate ? `due ${item.dueDate}` : ''].filter(Boolean).join(', ')}
                      </span>
                    )}
                  </span>
                </li>
              ))}
            </ul>
          </section>
        )}

        {snapshot.chapters.length > 0 && (
          <section className="card stack">
            <h2 className="h3">Chapters</h2>
            <ol className="chapter-list">
              {snapshot.chapters.map((chapter, index) => (
                <li key={index} className="chapter">
                  <div className="chapter-head">
                    <span className="chapter-index" aria-hidden>{index + 1}</span>
                    <h3 className="h3 grow">{chapter.title}</h3>
                    {chapter.startMs !== null && <span className="time-chip time-chip--static">{formatTimestamp(chapter.startMs)}</span>}
                  </div>
                  <ul className="note-list">
                    {chapter.points.map((point, i) => (
                      <li key={i} className="note-item">
                        <span className="bullet" aria-hidden />
                        <span>{point.text}</span>
                      </li>
                    ))}
                  </ul>
                </li>
              ))}
            </ol>
          </section>
        )}

        <footer className="tiny muted">Shared with NoteAI. Anyone with this link can read these notes until it expires or is revoked.</footer>
      </article>
    </main>
  );
}
